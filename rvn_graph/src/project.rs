use crate::{transpile_with_origins, GraphDocument, GraphKind, TranspiledScript, TranspiledScriptWithOrigins, GraphStatementOrigin};
use rvn_parser::{Script, Statement};
use std::collections::{BTreeMap, BTreeSet};

/// Only the spelling emitted by the project exporter, including collision suffixes.
/// This identifies source transport, never a Native node or runtime authority.
pub(crate) fn is_project_transport_end_name(name: &str) -> bool {
    name.strip_prefix("__blueprint_project_end")
        .is_some_and(|suffix| suffix.bytes().all(|byte| byte == b'_'))
}

/// A project footer is one final, empty, ordinary label declaration.
pub(crate) fn project_transport_end(script: &Script) -> Option<&str> {
    let Some(Statement::Label { name }) = script.last() else { return None; };
    if !is_project_transport_end_name(name) { return None; }
    (script.iter().filter(|statement| matches!(statement,
        Statement::Label { name: candidate } | Statement::SceneLabel { name: candidate }
        if candidate == name)).count() == 1).then_some(name.as_str())
}

/// An exact scheduled v2 Jump/Return exits its graph just like its bare form.
/// This avoids unreachable transport only; source identity/kind/version/body
/// validation still runs independently and grants no execution authority.
pub(crate) fn is_unconditional_graph_exit(statement: &Statement) -> bool {
    matches!(statement, Statement::Jump { .. } | Statement::Return)
        || matches!(statement, Statement::ScheduledConsumer { version: 2, body, .. }
            if matches!(body.as_slice(), [Statement::Jump { .. } | Statement::Return]))
}

/// Compile all supplied documents before the caller writes any output.
/// Input order is deterministic: init documents, start, then named labels.
pub fn transpile_project(graphs: &[GraphDocument]) -> Result<TranspiledScript, String> {
    let compiled = transpile_project_with_origins(graphs)?;
    Ok(TranspiledScript { source: compiled.source, ast: compiled.ast })
}

pub fn transpile_project_with_origins(graphs: &[GraphDocument]) -> Result<TranspiledScriptWithOrigins, String> {
    if graphs.iter().any(|g|g.library1027.is_some()){return Err("Qualified Library graphs require actual scoped project resources".into())}
    transpile_project_context1027(graphs,None)
}
pub(crate) fn transpile_project_library1027<'a>(graphs:&'a[GraphDocument],all:&'a[GraphDocument],resources:&'a crate::LibraryGraphResources1027<'a>)->Result<TranspiledScriptWithOrigins,String>{
    transpile_project_context1027(graphs,Some((all,resources)))
}
fn transpile_project_context1027<'a>(graphs:&'a[GraphDocument],library:Option<(&'a[GraphDocument],&'a crate::LibraryGraphResources1027<'a>)>)->Result<TranspiledScriptWithOrigins,String>{
    crate::validate_text_owners(graphs)?;
    crate::unit_graph_source1003::validate_project(library.map(|(all,_)|all).unwrap_or(graphs))?;
    let mut resolved = graphs.to_vec();
    resolve_label_references(&mut resolved)?;
    let graphs = resolved.as_slice();
    if graphs.is_empty() {
        return Err("Le projet ne contient aucun graphe".into());
    }
    let mut ordered: Vec<_> = graphs.iter().collect();
    ordered.sort_by_key(|g| match &g.kind {
        GraphKind::Function { name } | GraphKind::UnitFunction { name } | GraphKind::Screen { name } | GraphKind::Handler { name } => {
            (0, name.clone())
        }
        GraphKind::Init => (1, String::new()),
        GraphKind::Label { name } if name == "start" => (2, name.clone()),
        GraphKind::Label { name } => (3, name.clone()),
        _ => (4, String::new()),
    });
    let mut characters = BTreeMap::new();
    for graph in &ordered {
        for (id, name) in &graph.characters {
            if characters
                .insert(id.clone(), name.clone())
                .is_some_and(|old| old != *name)
            {
                return Err(format!(
                    "Le personnage {id} porte des noms différents selon les graphes"
                ));
            }
        }
    }
    let mut source = String::from("// Generated by rust-VN Blueprint — project export\n");
    let mut mappings = Vec::new();
    fn record(origin: &GraphStatementOrigin, offset: usize, mappings: &mut Vec<(std::ops::Range<usize>, crate::GraphId, crate::NodeId)>) {
        if let (Some(graph), Some(node)) = (origin.graph, origin.node) {
            mappings.push((origin.span.range.start + offset..origin.span.range.end + offset, graph, node));
        }
        for child in &origin.children { record(child, offset, mappings); }
    }
    // A disconnected execution output ends that graph; it must not execute
    // whichever document happened to sort next in the project export.
    // Reuse an imported export sentinel instead of creating another graph on
    // every script → Blueprint → script round-trip.
    let native_project = ordered.iter().any(|graph| !graph.inspector_evaluation.is_legacy());
    let existing_end = ordered.iter().find(|graph| matches!(&graph.kind, GraphKind::Label { name }
        if name.starts_with("__blueprint_project_end")
            && (!native_project || is_project_transport_end_name(name)))
        && graph.nodes.values().all(|node| node.kind == crate::NodeKind::Label));
    let mut end_label = existing_end
        .and_then(|graph| match &graph.kind {
            GraphKind::Label { name } => Some(name.clone()),
            _ => None,
        })
        .unwrap_or_else(|| "__blueprint_project_end".to_string());
    while existing_end.is_none()
        && ordered.iter().any(|g| {
            matches!(&g.kind, GraphKind::Label { name } if name == &end_label)
                || g.nodes.values().any(|n| {
                    n.properties.get("label")
                        == Some(&crate::PropertyValue::String(end_label.clone()))
                })
        })
    {
        end_label.push('_');
    }
    for (index, graph) in ordered.iter().enumerate() {
        if existing_end.is_some_and(|end| end.graph_id == graph.graph_id) {
            continue;
        }
        let mut graph = (*graph).clone();
        graph.characters = if index == 0 {
            characters.clone()
        } else {
            BTreeMap::new()
        };
        let compiled = if let Some((all,resources))=library { crate::codegen::transpile_library_graph1027(&graph,all,resources) }else if graph.inspector_evaluation.is_legacy() {
            if crate::uses_unit_context1026(&graph) { crate::codegen::transpile_unit_in_project(&graph,graphs) } else { transpile_with_origins(&graph) }
        } else {
            crate::native_frame_preparation::prepare_native_unchecked(&graph)
        }.map_err(|e| format!("Graphe {:?} : {e}", graph.kind))?;
        for origin in &compiled.origins { record(origin, source.len(), &mut mappings); }
        source.push_str(&compiled.source);
        // An explicit final jump already leaves this graph. Emitting another
        // jump after it creates unreachable code and spurious CLI warnings.
        if matches!(graph.kind, GraphKind::Label { .. })
            && !matches!(
                compiled.ast.last(),
                Some(Statement::Jump { .. } | Statement::Return)
            )
        {
            source.push_str(&format!("    jump {end_label}\n"));
        }
        source.push('\n');
    }
    source.push_str(&format!("label {end_label}\n"));
    let context = if graphs.iter().any(|graph| graph.narrative.is_some()) {
        rvn_parser::NarrativeContext::ExplicitScenes
    } else { rvn_parser::NarrativeContext::Legacy };
    let parsed = rvn_parser::parse_with_origins(&source, context).map_err(|e| e.to_string())?;
    // Metadata grants contextual fragment editing, but a complete project
    // without imports must establish that context through a real entry.
    if context == rvn_parser::NarrativeContext::ExplicitScenes
        && !parsed.script.iter().any(|statement| matches!(statement, Statement::Use { .. })) {
        rvn_parser::parse_program(&source)?;
    }
    validate_project_script(&parsed.script, true)?;
    // Only the complete candidate contains the real project Init/global and
    // Scene context. Standalone scope import cannot invent those declarations.
    for graph in graphs.iter().filter(|graph|!graph.inspector_evaluation.is_legacy()) {
        crate::native_frame_preparation::prepare_native_frame_graph_in_context(graph,Some(&parsed.script))
            .map_err(|e|format!("Graphe {:?} : {e}",graph.kind))?;
    }
    let origins = parsed.spans.iter().map(|span| crate::codegen::map_statement_origin(span, &mappings)).collect();
    Ok(TranspiledScriptWithOrigins { source, ast: parsed.script, context, origins })
}

/// A bound label uses graph identity, never its editable display name.
/// The string remains a compatibility cache for single-document exports.
pub fn resolve_label_references(graphs: &mut [GraphDocument]) -> Result<(), String> {
    let mut labels = BTreeMap::new();
    let bound: BTreeSet<String> = graphs
        .iter()
        .flat_map(|g| g.nodes.values())
        .filter_map(|n| match n.properties.get("target_graph") {
            Some(crate::PropertyValue::String(id)) => Some(id.clone()),
            _ => None,
        })
        .collect();
    for graph in graphs.iter() {
        if let GraphKind::Label { name } = &graph.kind {
            let id = serde_json::to_string(&graph.graph_id).map_err(|e| e.to_string())?;
            if labels.insert(id.clone(), name.clone()).is_some() && bound.contains(&id) {
                return Err(format!("Identité de graphe dupliquée : {id}. Les copies doivent avoir une identité distincte."));
            }
        }
    }
    for graph in graphs {
        for node in graph
            .nodes
            .values_mut()
            .filter(|n| n.kind == crate::NodeKind::LabelValue)
        {
            if let Some(crate::PropertyValue::String(id)) = node.properties.get("target_graph") {
                let name = labels.get(id).ok_or_else(|| {
                    format!(
                        "Référence de label cassée au nœud {:?} : graphe {id} absent",
                        node.id
                    )
                })?;
                node.properties
                    .insert("label".into(), crate::PropertyValue::String(name.clone()));
            }
        }
    }
    Ok(())
}

/// Also usable after resolving `use` files, so unresolved destinations cannot
/// escape project validation just because an import was present.
pub fn validate_project_script(
    script: &Script,
    allow_external_imports: bool,
) -> Result<(), String> {
    fn walk<'a>(statements: &'a [Statement], all: &mut Vec<&'a Statement>) {
        for statement in statements {
            all.push(statement);
            match statement {
                Statement::Init { body } => walk(body, all),
                Statement::While { body, .. } | Statement::ForEach { body, .. } | Statement::ForLoopWithBreak{body,..}=>walk(body,all),
                Statement::Sequence{branches}=>for branch in branches{walk(branch,all);},
                Statement::If {
                    then_branch,
                    else_branch,
                    ..
                } => {
                    walk(then_branch, all);
                    walk(else_branch, all);
                }
                Statement::Choice { options } => {
                    for option in options {
                        walk(&option.body, all);
                    }
                }
                Statement::Imagemap { hotspots, .. } => {
                    for hotspot in hotspots {
                        walk(&hotspot.body, all);
                    }
                }
                _ => {}
            }
        }
    }
    let mut all = Vec::new();
    walk(script, &mut all);
    let mut labels = BTreeSet::new();
    for statement in &all {
        if let Statement::Label { name } | Statement::SceneLabel { name } = statement {
            if !labels.insert(name.as_str()) {
                return Err(format!("Label dupliqué dans le projet : {name}"));
            }
        }
    }
    let imports = all.iter().any(|s| matches!(s, Statement::Use { .. }));
    if let Some(error) =
        rvn_parser::validate_logic(script, allow_external_imports && imports).first()
    {
        return Err(error.french.clone());
    }
    if !allow_external_imports || !imports {
        for statement in all {
            let target = match statement {
                Statement::Jump { target } | Statement::Call { target } => Some(target.as_str()),
                Statement::Timer { action, .. } => action.split_whitespace().nth(1),
                _ => None,
            };
            if let Some(target) = target {
                if !labels.contains(target) {
                    return Err(format!("Label de destination introuvable : {target}"));
                }
            }
        }
    }
    Ok(())
}
